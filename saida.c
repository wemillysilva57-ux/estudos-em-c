#include <stdio.h>
int main() {
// \n é pra pular para a próxima linha
    printf ("olá tudo bem?\n");
// %d.aloca u espaço para o valor inteiro 
    printf("valor inteiro: %d.\n",10);
// %f.aloca u espaço para o valor float
    printf("valor float: %f.\n",10.5);
// %.2f.aloca u espaço para o valor float com 2 casas decimais
    printf("valor float com 2 casas decimais: %.2f.\n",10.5);
// %c.aloca u espaço para o valor char
    printf("dado de texto,char:%c.\n",'a');
// %s.aloca u espaço para o valor string
    printf("dado de texto,string:%s.\n","olá, mundo!");
}